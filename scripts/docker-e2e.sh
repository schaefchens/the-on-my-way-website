#!/usr/bin/env bash
# Fixture end-to-end run of the backend Docker image: no phone, no API, no live host.
#
#   scripts/docker-e2e.sh [--no-build] [--keep] [--skip-playwright] [--skip-restart]
#
# 1. builds omw-backend:dev (backend/Dockerfile, this machine's architecture) unless --no-build;
# 2. starts it with backend/compose.yaml + a generated override (.cache/docker/e2e/compose.yaml):
#    compose project "omw-e2e" (never the real "omw" project, its container or its state volume),
#    WA_MODE=fixture with fixtures/generated mounted read-only, NO env file (the repo .env is not
#    read, so no SFTP_*/API_* value reaches the container), the control UI on 127.0.0.1 only and a
#    local publish target writing to the bind-mounted .cache/docker/e2e/out (without a public URL:
#    the container cannot reach the host's static server for the post-deploy HTTP check);
# 3. imports the owner fixtures (trip, notes, story; locales de,en,ar) with a one-shot
#    `docker compose run`, then waits for ingest -> media pipeline -> generate -> local publish;
# 4. runs the generated-site Playwright spec on the host against the published folder;
# 5. checks a graceful `docker compose stop` (clean shutdown logged, exit code 0, SQLite
#    integrity_check ok) and a restart (no new capture, no new site version, nothing uploaded);
# 6. removes the containers, network and state volume it created (unless --keep).
#
# Needs: Docker (compose v2.24+), the host's `pnpm install`, `pnpm fixtures` (fixtures/generated)
# and Playwright's Chromium (PLAYWRIGHT_BROWSERS_PATH, default .cache/ms-playwright).
# Ports (127.0.0.1 only): OMW_DOCKER_CONTROL_PORT (default 19180), OMW_DOCKER_SITE_PORT (19181).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
W="$ROOT/.cache/docker/e2e"
PROJECT=omw-e2e
IMAGE="${OMW_DOCKER_IMAGE:-omw-backend:dev}"
CONTROL_PORT="${OMW_DOCKER_CONTROL_PORT:-19180}"
SITE_PORT="${OMW_DOCKER_SITE_PORT:-19181}"
SITE_URL="http://127.0.0.1:${SITE_PORT}"
BUILD=1 KEEP=0 PLAYWRIGHT=1 RESTART=1
for a in "$@"; do
  case "$a" in
    --no-build) BUILD=0 ;;
    --keep) KEEP=1 ;;
    --skip-playwright) PLAYWRIGHT=0 ;;
    --skip-restart) RESTART=0 ;;
    -h | --help) awk 'NR > 1 && /^#/ { sub(/^# ?/, ""); print; next } NR > 1 { exit }' "$0"; exit 0 ;;
    *) echo "unknown option: $a" >&2; exit 2 ;;
  esac
done

log() { printf '\n[docker-e2e] %s\n' "$*"; }
fail() { printf '\n[docker-e2e] FAILED: %s\n' "$*" >&2; exit 1; }

[ -f "$ROOT/fixtures/generated/index.json" ] || fail "fixtures/generated is missing: run \`pnpm fixtures\` first"
docker compose version >/dev/null || fail "docker compose v2 is required"

dc() { docker compose -p "$PROJECT" -f "$ROOT/backend/compose.yaml" -f "$W/compose.yaml" "$@"; }

cleanup() {
  local code=$?
  if [ "$KEEP" = 1 ]; then
    log "kept: containers/volume of project $PROJECT (remove: docker compose -p $PROJECT -f backend/compose.yaml -f $W/compose.yaml down -v)"
  elif [ -f "$W/compose.yaml" ]; then
    dc logs --no-color >"$W/backend.log" 2>&1 || true
    dc down -v --remove-orphans >/dev/null 2>&1 || true
  fi
  exit "$code"
}

# ------------------------------------------------------------------------------------- setup
if [ "$BUILD" = 1 ]; then
  log "building $IMAGE"
  t0=$(date +%s)
  docker build -f "$ROOT/backend/Dockerfile" -t "$IMAGE" "$ROOT"
  log "build took $(($(date +%s) - t0)) s"
fi
docker image inspect "$IMAGE" >/dev/null 2>&1 || fail "image $IMAGE not found (build it or drop --no-build)"

# A previous --keep run: remove its containers and volume first (fresh state every run).
if [ -f "$W/compose.yaml" ]; then dc down -v --remove-orphans >/dev/null 2>&1 || true; fi
rm -rf "$W/data" "$W/out"
mkdir -p "$W/data/config" "$W/out"

(
  umask 077
  printf 'CONTROL_TOKEN=%s\n' "$(openssl rand -hex 24)" >"$W/e2e.env"
  cat >"$W/data/config/targets.json" <<JSON
{ "format": 1, "targets": [ { "id": "local-e2e", "kind": "local", "enabled": true,
  "publicBaseUrl": null, "dir": "/publish",
  "createdAt": "2026-01-01T00:00:00.000Z", "updatedAt": "2026-01-01T00:00:00.000Z" } ] }
JSON
)
TOKEN="$(sed -n 's/^CONTROL_TOKEN=//p' "$W/e2e.env")"

cat >"$W/compose.yaml" <<YAML
# Generated by scripts/docker-e2e.sh: fixture-mode override of backend/compose.yaml.
services:
  backend:
    image: ${IMAGE}
    build: !reset null
    env_file: !override
      - path: ${W}/e2e.env
        format: raw
    environment:
      WA_MODE: fixture
      FIXTURES_DIR: /fixtures
      SITE_PUBLIC_URL: ${SITE_URL}/
      LOG_LEVEL: info
      SFTP_HOST: ""
      API_BASE_URL: ""
      API_TOKEN: ""
      NTFY_URL: ""
    ports: !override
      - "127.0.0.1:${CONTROL_PORT}:8787"
    labels:
      omw.project: omw
    volumes: !override
      - omw-e2e-state:/data
      - ${W}/data:/app/backend/data
      - ${ROOT}/fixtures/generated:/fixtures:ro
      - ${W}/out:/publish
volumes:
  omw-e2e-state:
    labels:
      omw.project: omw
YAML
dc config --quiet || fail "compose config is invalid"
trap cleanup EXIT

status_json() {
  curl -fsS --max-time 5 -H "Authorization: Bearer ${TOKEN}" "http://127.0.0.1:${CONTROL_PORT}/api/status"
}

# Prints "<ready 0|1> <summary>" for a status document on stdin.
STATUS_JS='
let s = ""; process.stdin.on("data", (d) => (s += d)).on("end", () => {
  const st = JSON.parse(s);
  const by = st.captures.byState;
  // awaiting_media is not "busy": in fixture mode a pending download never resolves (by design).
  const busy = ["received", "archived", "processed"].reduce((n, k) => n + (by[k] ?? 0), 0);
  const gen = st.build.last?.version ?? null;
  const pub = st.publish.state.lastVersion ?? null;
  const ready = st.captures.total >= Number(process.argv[1]) && busy === 0 && !st.build.running &&
    !st.build.pending && !st.publish.running && !st.publish.queued && gen !== null && pub === gen;
  console.log(`${ready ? 1 : 0} captures=${JSON.stringify(by)} generated=v${gen} published=v${pub} ` +
    `uploaded=${st.publish.lastResults.map((r) => r.targetId + ":" + r.uploaded).join(",")} ` +
    `wa=${st.wa.state} lastError=${st.publish.state.lastError ?? st.build.lastError ?? "-"}`);
});'

wait_settled() {
  local min="$1" deadline=$(($(date +%s) + ${2:-300})) prev="" line
  while [ "$(date +%s)" -lt "$deadline" ]; do
    if line="$(status_json 2>/dev/null | node -e "$STATUS_JS" "$min")"; then
      if [ "${line%% *}" = 1 ]; then
        # Settled twice in a row (a debounced generate may still be about to start).
        [ "$prev" = "$line" ] && { echo "${line#* }"; return 0; }
        prev="$line"
      else
        prev=""
      fi
    fi
    sleep 3
  done
  echo "${line:-no status}" >&2
  return 1
}

wait_healthy() {
  local deadline=$(($(date +%s) + ${1:-120})) h
  while [ "$(date +%s)" -lt "$deadline" ]; do
    h="$(docker inspect -f '{{.State.Health.Status}}' "$(dc ps -q backend)" 2>/dev/null || true)"
    [ "$h" = healthy ] && return 0
    sleep 2
  done
  return 1
}

# ------------------------------------------------------------------------------ owner content
log "owner-import (one-shot container, before the daemon starts)"
dc run --rm --no-deps backend backend owner-import /fixtures/owner.json --locales=de,en,ar

# ------------------------------------------------------------------------------------- start
log "starting the backend (fixture mode)"
t0=$(date +%s)
dc up -d backend
wait_healthy 150 || fail "container did not become healthy"
log "healthy after $(($(date +%s) - t0)) s"
EXPECTED=$(node -e 'console.log(require(process.argv[1]).statuses.length)' "$ROOT/fixtures/generated/index.json")
SUMMARY="$(wait_settled "$EXPECTED" 300)" || fail "pipeline did not settle"
log "settled after $(($(date +%s) - t0)) s: $SUMMARY"

# Control UI: published on 127.0.0.1 only, /healthz answers, the token is required.
PORTS="$(docker port "$(dc ps -q backend)" 8787/tcp)"
[ "$PORTS" = "127.0.0.1:${CONTROL_PORT}" ] || fail "control port mapping is '$PORTS', expected 127.0.0.1:${CONTROL_PORT} only"
curl -fsS "http://127.0.0.1:${CONTROL_PORT}/healthz" | grep -q '"omw-backend"' || fail "/healthz"
code=$(curl -s -o /dev/null -w '%{http_code}' "http://127.0.0.1:${CONTROL_PORT}/api/status")
[ "$code" = 401 ] || fail "/api/status without a token answered $code, expected 401"
log "control UI: ${PORTS} (loopback only), /healthz ok, /api/status requires the token"

[ -f "$W/out/data/manifest.json" ] || fail "nothing was published to $W/out"

# -------------------------------------------------------------------------------- playwright
if [ "$PLAYWRIGHT" = 1 ]; then
  log "Playwright (generated-site spec) against $W/out on $SITE_URL"
  (cd "$ROOT" && OMW_GENERATED_DIR="$W/out" OMW_GENERATED_URL="$SITE_URL" \
    PLAYWRIGHT_BROWSERS_PATH="${PLAYWRIGHT_BROWSERS_PATH:-$ROOT/.cache/ms-playwright}" \
    pnpm exec playwright test -c frontend/site/playwright.generated.config.ts)
fi

# ------------------------------------------------------------------------ stop and restart
if [ "$RESTART" = 1 ]; then
  BEFORE="$SUMMARY"
  log "graceful stop"
  t0=$(date +%s)
  dc stop backend
  CID="$(dc ps -aq backend)"
  EXIT="$(docker inspect -f '{{.State.ExitCode}}' "$CID")"
  log "stopped in $(($(date +%s) - t0)) s, exit code $EXIT"
  [ "$EXIT" = 0 ] || fail "exit code $EXIT after docker compose stop"
  LOGS="$(dc logs --no-color backend)"
  grep -q '"msg":"shutting down"' <<<"$LOGS" || fail "no 'shutting down' log line"
  grep -q '"msg":"stopped"' <<<"$LOGS" || fail "no 'stopped' log line"
  INTEGRITY="$(dc run --rm --no-deps --entrypoint node backend -e \
    "const D=require('/app/backend/node_modules/better-sqlite3');const db=new D('/data/store.db',{readonly:true});console.log(db.pragma('integrity_check',{simple:true}));" )"
  [ "$INTEGRITY" = ok ] || fail "store integrity_check: $INTEGRITY"
  log "store integrity_check: ok; lock released: $(dc run --rm --no-deps --entrypoint sh backend -c 'test -e /data/backend.lock && echo no || echo yes')"

  log "restart"
  SINCE="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  sleep 1
  dc start backend
  wait_healthy 150 || fail "container did not become healthy after the restart"
  AFTER="$(wait_settled "$EXPECTED" 120)" || fail "did not settle after the restart"
  log "after restart: $AFTER"
  # Same captures and the same site version; nothing ingested, processed or uploaded again.
  [ "${BEFORE%% generated=*}" = "${AFTER%% generated=*}" ] || fail "captures changed across the restart"
  g1="$(sed -E 's/.*generated=(v[0-9]+).*/\1/' <<<"$BEFORE")"
  g2="$(sed -E 's/.*generated=(v[0-9]+).*/\1/' <<<"$AFTER")"
  [ "$g1" = "$g2" ] || fail "site version changed across the restart ($g1 -> $g2)"
  RLOGS="$(dc logs --no-color --since "$SINCE" backend)"
  grep -q '"msg":"backend started"' <<<"$RLOGS" || fail "no 'backend started' after the restart"
  for m in 'status ingested' 'capture ready'; do
    n="$(grep -c "\"msg\":\"$m\"" <<<"$RLOGS" || true)"
    [ "$n" = 0 ] || fail "restart repeated work: $n x '$m'"
  done
  # The startup generate is incremental: it must find nothing to change.
  if grep '"msg":"site generated"' <<<"$RLOGS" | grep -Eq '"changed":[1-9]'; then fail "the restart regenerated pages"; fi
  if grep -Eq '"uploaded":[1-9]' <<<"$RLOGS"; then fail "the restart uploaded files again"; fi
  log "restart ok: nothing ingested or processed again, startup generate changed 0 files, site still $g2, nothing uploaded"
fi

log "OK"
